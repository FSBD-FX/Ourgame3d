def desc(p):
    b = p.read_bytes()
    return {'path': p.as_posix(), 'bytes': len(b), 'sha256': hashlib.sha256(b).hexdigest()}


def write(name, value):
    p = OUT / name
    assert not p.exists() or revise_unfrozen, p
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(json.dumps(value, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    return p


def polygon(points):
    im = Image.new('L', (512, 512), 0)
    ImageDraw.Draw(im).polygon([tuple(p) for p in points], fill=255)
    return np.asarray(im) != 0


def premultiplied(x):
    return np.concatenate((x[:, :, :3].astype(np.uint32) * x[:, :, 3:4],
                           x[:, :, 3:4].astype(np.uint32) * 255), axis=2)


